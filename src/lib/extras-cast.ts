import type { Band } from "./orbit.ts";

// Who the extras are and what they say (ADR 0021; the schedule is in
// extras.ts). Invented people, written to read like the people who use the
// app: a few regulars with handles and habits of their own, and a crowd of
// one-off visitors who never claim a handle. Nobody real: no handle is a
// person's name, no line speaks as a child, nobody mourns someone
// invented. Every callsign and line passes the launch form's own rules
// (spec/extras.test.ts).
//
// Nothing they say can be checked against the sky and found false: no line
// says something happened to one of theirs (it can be looked up), that
// they're listening (they never are: "heard by" is people only), or which
// band they fly unless it does.

// When a line fits: only at some hours in Canberra (from, to; wrapping past
// midnight: "9pm at the bus interchange" isn't said at lunchtime), in some
// months there ("enjoy your spring"), from some bands ("going high"), or
// only from a satellite that will be brought down or boosted ("I'll bring
// this down when I'm done").
export interface Fit {
  hours?: [number, number];
  months?: number[];
  bands?: Band[];
  does?: "deorbit" | "boost";
}
export type Line = string | ({ text: string } & Fit);
const at = (from: number, to: number, text: string): Line => ({ text, hours: [from, to] });
const flying = (bands: Band[], text: string): Line => ({ text, bands });
const promising = (does: "deorbit" | "boost", text: string, bands?: Band[]): Line => ({ text, does, ...(bands ? { bands } : {}) });
// in Canberra's spring (or Edinburgh's autumn), September to November
const SPRING = [9, 10, 11];
const inSpring = (text: string, hours?: [number, number]): Line => ({ text, months: SPRING, ...(hours ? { hours } : {}) });
export const textOf = (line: Line): string => (typeof line === "string" ? line : line.text);

export interface Regular {
  // their owner cookie is "extra:" and this
  key: string;
  // the handle they claimed, or null: they launch without one, like most
  handle: string | null;
  // how many days in ten they come, roughly: a visit a day is 1
  perDay: number;
  // the hours they're about, in Canberra (from, to; wrapping past midnight)
  hours: [number, number];
  // the chance a visit is one launch, two, three
  visits: number[];
  bands: Partial<Record<Band, number>>;
  // the chance a launch answers the day's question
  answers: number;
  // the chance they bring one down later, or boost it
  deorbits: number;
  boosts: number;
  // what they call their nth satellite (from 0, counted in the record):
  // people keep a habit
  callsign: (n: number) => string;
  lines: Line[];
}

const numbered = (name: string, from = 1) => (n: number) => `${name} ${n + from}`;
const hyphened = (name: string, from = 1) => (n: number) => `${name}-${n + from}`;
// a list of names in turn, numbered from the second time round
const inTurn = (names: string[]) => (n: number) => {
  const name = names[n % names.length];
  const round = Math.floor(n / names.length);
  return round === 0 ? name : `${name} ${round + 1}`;
};

